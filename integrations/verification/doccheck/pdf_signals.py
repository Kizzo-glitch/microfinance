"""
Document checking — Layer 3: PDF structural tamper signals (pypdf).

These read the ORIGINAL PDF FILE, not the OCR text — the tamper signals live in
the PDF structure, which OCR (rasterize->Tesseract) throws away. So these run
separately, and ONLY on native-PDF uploads. A photographed/scanned statement
has no PDF structure to inspect, and that's correctly reported as inconclusive,
never as a pass or fail.

HONESTY: every signal here is MODERATE at most. A statement "made in Canva" is
suspicious, not proof — plenty of legitimate documents are re-saved. These
inform a human; they never condemn on their own. The one strong arithmetic
signal stays the running balance (Layer 2), not these.

requires: pypdf
"""

from .framework import CheckResult, Outcome
from pypdf import PdfReader

# Producer/creator strings that strongly suggest a document-design or
# word-processing tool rather than a bank's statement generator.
SUSPICIOUS_PRODUCERS = [
    "canva", "word", "microsoft office", "powerpoint", "photoshop",
    "illustrator", "gimp", "libreoffice", "pages", "indesign", "paint",
]
# Producers that are normal for genuine statements (bank/report generators).
BENIGN_HINTS = ["itext", "jasper", "reportlab", "pdfbox", "fpdf", "wkhtmltopdf"]


def _open(file_path):
    
    return PdfReader(file_path)


def check_pdf_producer(file_path):
    """MODERATE. Flag if the PDF was produced by a design/word tool."""
    try:
        reader = _open(file_path)
        meta = reader.metadata or {}
    except Exception as e:
        return CheckResult(
            "pdf_producer", "PDF origin looks like a statement generator",
            Outcome.INCONCLUSIVE, "moderate",
            f"Could not read PDF metadata: {e}")

    producer = (meta.get("/Producer") or "").lower()
    creator = (meta.get("/Creator") or "").lower()
    blob = f"{producer} {creator}".strip()

    if not blob:
        return CheckResult(
            "pdf_producer", "PDF origin looks like a statement generator",
            Outcome.INCONCLUSIVE, "moderate",
            "The PDF carries no producer/creator metadata to assess.")

    hit = next((s for s in SUSPICIOUS_PRODUCERS if s in blob), None)
    if hit:
        return CheckResult(
            "pdf_producer", "PDF origin looks like a statement generator",
            Outcome.FAIL, "moderate",
            detail=(f"This PDF reports it was produced with '{hit}' "
                    f"(producer/creator: '{blob}'). Bank statements are normally "
                    f"generated by the bank's system, not a document-design or "
                    f"word-processing tool. Worth a closer look."),
            data={"producer": producer, "creator": creator})

    return CheckResult(
        "pdf_producer", "PDF origin looks like a statement generator",
        Outcome.PASS, "moderate",
        f"PDF producer/creator ('{blob}') is not a known document-editing tool.")


def check_pdf_incremental_saves(file_path):
    """
    MODERATE. A PDF edited after creation often has multiple cross-reference
    sections (incremental updates). More than one '%%EOF' / 'startxref' is a
    hint the file was opened and re-saved — common with edited statements.
    """
    try:
        with open(file_path, "rb") as f:
            raw = f.read()
    except Exception as e:
        return CheckResult(
            "pdf_incremental", "No sign of post-creation edits",
            Outcome.INCONCLUSIVE, "moderate",
            f"Could not read the PDF file: {e}")

    eof_count = raw.count(b"%%EOF")
    startxref_count = raw.count(b"startxref")

    # A clean, single-write PDF typically has one of each. Several suggests
    # incremental updates (edits). Two is common/benign (linearized PDFs), so
    # only flag at 3+ to avoid false alarms.
    if eof_count >= 3 or startxref_count >= 3:
        return CheckResult(
            "pdf_incremental", "No sign of post-creation edits",
            Outcome.FAIL, "moderate",
            detail=(f"The PDF contains {eof_count} end-of-file markers and "
                    f"{startxref_count} cross-reference sections, which usually "
                    f"means it was opened and re-saved several times after it was "
                    f"first created. That can be innocent, but it's a sign to "
                    f"check the figures carefully."),
            data={"eof_count": eof_count, "startxref_count": startxref_count})

    return CheckResult(
        "pdf_incremental", "No sign of post-creation edits",
        Outcome.PASS, "moderate",
        "The PDF shows no sign of having been re-saved after creation.")


def pdf_signal_checks(file_path):
    """
    Build check callables bound to this file_path, shaped like the other checks
    ((extracted, context) -> CheckResult) so they slot into run_checks / the
    statement assessment via `extra_checks`.
    """
    def _producer(extracted, context):
        return check_pdf_producer(file_path)

    def _incremental(extracted, context):
        return check_pdf_incremental_saves(file_path)

    _producer.check_label = "PDF origin"
    _incremental.check_label = "PDF edit history"
    return [_producer, _incremental]


def is_pdf(file_path):
    return str(file_path).lower().endswith(".pdf")